import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { keccak256, type Hex } from "viem";

const ARTIFACT = fileURLToPath(new URL("../../contracts/out/BoardRegistry.sol/BoardRegistry.json", import.meta.url));
const DEPLOYMENTS = fileURLToPath(new URL("../../contracts/deployments/testnet.json", import.meta.url));
const OUT_DIR = fileURLToPath(new URL("../src/abi/", import.meta.url));
const OUT = fileURLToPath(new URL("../src/abi/boardRegistry.ts", import.meta.url));

function main(): void {
  if (!existsSync(ARTIFACT)) throw new Error(`No build output at ${ARTIFACT}. Run forge build in packages/contracts first.`);
  const artifact = JSON.parse(readFileSync(ARTIFACT, "utf8")) as { abi?: unknown; deployedBytecode?: { object?: unknown } };
  if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) throw new Error("The build output has no ABI.");
  const runtime = artifact.deployedBytecode?.object;
  if (typeof runtime !== "string" || !/^0x[0-9a-fA-F]{2,}$/.test(runtime)) throw new Error("The build output has no runtime code.");

  const deployed = JSON.parse(readFileSync(DEPLOYMENTS, "utf8")) as { BoardRegistry?: { address?: unknown; runtimeCodeHash?: unknown } };
  const recorded = deployed.BoardRegistry?.runtimeCodeHash;
  if (typeof recorded !== "string" || !/^0x[0-9a-f]{64}$/.test(recorded)) throw new Error(`${DEPLOYMENTS} records no BoardRegistry runtime code hash.`);
  // The ABI is only the deployed one if this build is the deployed build.
  const built = keccak256(runtime as Hex);
  if (built !== recorded) {
    throw new Error(`The build's runtime code hashes to ${built}, not ${recorded} as recorded at deploy. Refusing to write an ABI the live registry may not speak.`);
  }

  const header = [
    "// Generated by scripts/gen-abi.ts from packages/contracts/out/BoardRegistry.sol/BoardRegistry.json.",
    "// Do not edit by hand; run `npm run gen-abi` after a new deploy. The build it came from has the",
    `// runtime code keccak ${recorded}, the one recorded for the deployed registry.`,
  ].join("\n");
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT, `${header}\nexport const boardRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`, "utf8");
  console.log(`wrote src/abi/boardRegistry.ts: ${artifact.abi.length} ABI entries, runtime code keccak ${recorded}`);
}

try {
  main();
} catch (err) {
  console.error(err instanceof Error ? err.message : String(err));
  process.exitCode = 1;
}
